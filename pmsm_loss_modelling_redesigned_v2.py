# 24. Operating-map-aware sampler
def add_operating_bins(df):
    out = df.copy()

    out["_speed_bin"] = pd.qcut(
        out["speed_rpm"].rank(method="first"),
        q=N_SPEED_BINS,
        labels=False,
        duplicates="drop"
    )

    out["_torque_bin"] = pd.qcut(
        out["torque_nm"].rank(method="first"),
        q=N_TORQUE_BINS,
        labels=False,
        duplicates="drop"
    )

    out["_op_bin"] = (
        out["_speed_bin"].astype(str) + "_" +
        out["_torque_bin"].astype(str)
    )

    return out

def operating_map_sample(df, n, seed):
    rng = np.random.RandomState(seed)
    binned = add_operating_bins(df)

    bins = [g for _, g in binned.groupby("_op_bin")]
    rng.shuffle(bins)

    selected = []

    # First pass: one sample per occupied bin.
    for g in bins:
        if len(selected) >= n:
            break
        selected.append(
            g.sample(1, random_state=rng.randint(0, 2**31-1)).index[0]
        )

    # Add more if n is larger than number of occupied bins.
    remaining = binned.index.difference(selected)
    if len(selected) < n:
        extra_n = min(n-len(selected), len(remaining))
        extra = rng.choice(remaining.values, size=extra_n, replace=False)
        selected.extend(extra.tolist())

    return df.loc[selected].copy()

