# 14. Reduced-order model and material-model parasitic correction
def reduced_order_matrix(df):
    omega = df["omega_rad_s"].values.astype(float)
    torque = df["torque_nm"].values.astype(float)
    return np.column_stack([
        np.ones(len(df)),
        np.abs(omega),
        omega**2,
        torque**2,
        np.abs(omega*torque)
    ])

def fit_reduced_order(train_df):
    model = Ridge(alpha=1e-8, fit_intercept=False)
    model.fit(reduced_order_matrix(train_df), train_df["target_loss_W"].values)
    return model

def predict_reduced_order(model, df):
    return model.predict(reduced_order_matrix(df))

def fit_parasitic_correction(train_df):
    omega = train_df["omega_rad_s"].values.astype(float)
    A = np.column_stack([np.abs(omega), omega**2])
    residual = (
        train_df["target_loss_W"].values -
        train_df["P_physics_A_base_W"].values
    )
    return np.linalg.lstsq(A, residual, rcond=None)[0]

def predict_material_with_parasitic(df, coeffs):
    omega = df["omega_rad_s"].values.astype(float)
    correction = coeffs[0]*np.abs(omega) + coeffs[1]*omega**2
    return df["P_physics_A_base_W"].values + correction

# 15. ML features and model factories
def make_feature_frame(df, mode="basic"):
    out = pd.DataFrame(index=df.index)
    out["speed_rpm"] = df["speed_rpm"].astype(float)
    out["torque_nm"] = df["torque_nm"].astype(float)

    if mode in ("engineered", "with_physics"):
        out["abs_speed"] = np.abs(df["speed_rpm"].astype(float))
        out["speed_sq"] = df["speed_rpm"].astype(float)**2
        out["torque_sq"] = df["torque_nm"].astype(float)**2
        out["abs_speed_torque"] = np.abs(
            df["speed_rpm"].astype(float) * df["torque_nm"].astype(float)
        )

    if mode == "with_physics":
        out["physics_A_base_W"] = df["P_physics_A_base_W"].astype(float)

    return out

def make_polynomial_model():
    return Pipeline([
        ("poly", PolynomialFeatures(degree=2, include_bias=False)),
        ("scale", StandardScaler()),
        ("ridge", Ridge(alpha=1e-3))
    ])

def make_gbt():
    return HistGradientBoostingRegressor(
        max_iter=300,
        learning_rate=0.05,
        max_leaf_nodes=31,
        l2_regularization=1e-3,
        random_state=SEED
    )

def make_mlp(seed=SEED):
    return Pipeline([
        ("scale", StandardScaler()),
        ("mlp", MLPRegressor(
            hidden_layer_sizes=(32,32),
            activation="relu",
            solver="adam",
            max_iter=2000,
            early_stopping=True,
            validation_fraction=0.15,
            random_state=seed
        ))
    ])

# 16. Physics-guided neural network
class TorchMLP(nn.Module):
    def __init__(self, n_features):
        super().__init__()
        self.net = nn.Sequential(
            nn.Linear(n_features, 32),
            nn.ReLU(),
            nn.Linear(32, 32),
            nn.ReLU(),
            nn.Linear(32, 1)
        )

    def forward(self, x):
        return self.net(x).squeeze(-1)

def train_physics_guided_nn(X_train, y_train, physics_train, lam, epochs=250, lr=1e-3, seed=SEED):
    torch.manual_seed(seed)

    scaler = StandardScaler()
    Xs = scaler.fit_transform(X_train)

    X_t = torch.tensor(Xs, dtype=torch.float32)
    y_t = torch.tensor(np.asarray(y_train), dtype=torch.float32)
    p_t = torch.tensor(np.asarray(physics_train), dtype=torch.float32)

    model = TorchMLP(X_t.shape[1])
    optimizer = torch.optim.Adam(model.parameters(), lr=lr)

    for epoch in range(epochs):
        optimizer.zero_grad()
        pred = model(X_t)

        data_loss = nn.functional.mse_loss(pred, y_t)
        physics_loss = nn.functional.mse_loss(pred, p_t)
        loss = data_loss + lam*physics_loss

        loss.backward()
        optimizer.step()

    return model, scaler

def predict_torch(model, scaler, X):
    Xs = scaler.transform(X)
    Xt = torch.tensor(Xs, dtype=torch.float32)
    model.eval()
    with torch.no_grad():
        return model(Xt).cpu().numpy()

