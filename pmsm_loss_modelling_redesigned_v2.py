# 9. Estimate output-power lag relative to T*omega
def estimate_lag_seconds(time_s, reference, candidate, max_lag_s=2.0):
    t = np.asarray(time_s, dtype=float)
    x = np.asarray(reference, dtype=float)
    y = np.asarray(candidate, dtype=float)

    dt = np.median(np.diff(t))
    max_lag_samples = max(1, int(round(max_lag_s / dt)))

    x = x - np.mean(x)
    y = y - np.mean(y)

    corr = correlate(x, y, mode="full")
    lags = correlation_lags(len(x), len(y), mode="full")

    mask = np.abs(lags) <= max_lag_samples
    corr2 = corr[mask]
    lags2 = lags[mask]

    i = np.argmax(corr2)
    lag_samples = int(lags2[i])

    denom = np.sqrt(np.sum(x*x) * np.sum(y*y))
    corr_norm = corr2[i] / denom if denom > 0 else np.nan

    return lag_samples*dt, corr_norm

