# 12. Material-derived physics components
res_rows = eq_df.loc[
    eq_df["Parameter"].astype(str).str.contains("resistance", case=False, na=False)
]
Rs_ref = float(res_rows["Value"].iloc[0]) if len(res_rows) else 8.9462

def copper_resistance_at_temp(R_ref, temp_C, ref_temp_C=20.0, alpha_cu=0.00393):
    return R_ref * (1 + alpha_cu*(np.asarray(temp_C)-ref_temp_C))

def material_physics_components(df, Rs=Rs_ref, winding_temp_C=None):
    speed = df["speed_rpm"].values.astype(float)
    torque = df["torque_nm"].values.astype(float)

    Iq = torque / (1.5 * pole_pairs * lam_pm)

    if winding_temp_C is None:
        Rs_vec = np.full_like(Iq, Rs)
    else:
        Rs_vec = copper_resistance_at_temp(Rs, winding_temp_C)

    P_cu = 1.5 * Rs_vec * Iq**2

    f_e = np.abs(speed) * pole_pairs / 60
    specific_fe = Kh*f_e*(B_eff**alpha_fixed) + Ke*(f_e**2)*(B_eff**2)
    P_fe = specific_fe * stator_mass_kg

    return pd.DataFrame({
        "Iq_A": Iq,
        "P_copper_W": P_cu,
        "P_iron_W": P_fe,
        "P_physics_A_base_W": P_cu + P_fe
    }, index=df.index)

