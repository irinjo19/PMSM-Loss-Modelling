def cycle_energy_wh(time_s, power_w):
    t = np.asarray(time_s, dtype=float)
    p = np.asarray(power_w, dtype=float)
    if len(t) < 2:
        return np.nan
    trapz_fn = getattr(np, "trapz", getattr(np, "trapezoid", None))
    return trapz_fn(p, t) / 3600.0

def metrics_dict(y_true, y_pred, time_s=None, rel_floor=REL_ERR_MIN_LOSS_W):
    y_true = np.asarray(y_true, dtype=float)
    y_pred = np.asarray(y_pred, dtype=float)
    abs_err = np.abs(y_pred - y_true)
    mask = np.abs(y_true) >= rel_floor

    out = {
        "MAE_W": mean_absolute_error(y_true, y_pred),
        "RMSE_W": mean_squared_error(y_true, y_pred) ** 0.5,
        "R2": r2_score(y_true, y_pred),
        "MedianAbsErr_W": np.median(abs_err),
        "MedianRelErr_pct": (
            np.median(abs_err[mask] / np.abs(y_true[mask])) * 100
            if mask.any() else np.nan
        ),
        "MeanRelErr_pct": (
            np.mean(abs_err[mask] / np.abs(y_true[mask])) * 100
            if mask.any() else np.nan
        )
    }

    if time_s is not None:
        e_true = cycle_energy_wh(time_s, y_true)
        e_pred = cycle_energy_wh(time_s, y_pred)
        out["TrueEnergy_Wh"] = e_true
        out["PredEnergy_Wh"] = e_pred
        out["CycleEnergyErr_pct"] = (
            abs(e_pred - e_true) / abs(e_true) * 100
            if np.isfinite(e_true) and abs(e_true) > 1e-12 else np.nan
        )
    return out

