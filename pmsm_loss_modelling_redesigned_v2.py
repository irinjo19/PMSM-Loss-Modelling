# 18. Unified model suite
def run_model_suite(train_df, val_df, test_df, feature_mode="basic"):
    results = []
    predictions = {}

    y_train = train_df["target_loss_W"].values
    y_val = val_df["target_loss_W"].values
    y_test = test_df["target_loss_W"].values

    X_train = make_feature_frame(train_df, feature_mode).values
    X_val = make_feature_frame(val_df, feature_mode).values
    X_test = make_feature_frame(test_df, feature_mode).values

    # Material physics only: no drive-cycle fitting / no training dependence
    predictions["Material_physics_only"] = test_df["P_physics_A_base_W"].values.copy()

    # Physics A: material physics + speed-dependent nuisance correction
    # Calibrate nuisance correction on TRAIN only.
    parasitic = fit_parasitic_correction(train_df)
    p_train = predict_material_with_parasitic(train_df, parasitic)
    p_val = predict_material_with_parasitic(val_df, parasitic)
    p_test = predict_material_with_parasitic(test_df, parasitic)
    predictions["Physics_A"] = p_test

    # Reduced-order
    rom = fit_reduced_order(train_df)
    predictions["Reduced_order"] = predict_reduced_order(rom, test_df)

    # Polynomial
    poly = make_polynomial_model()
    poly.fit(X_train, y_train)
    predictions["Polynomial"] = poly.predict(X_test)

    # Gradient boosting
    gbt = make_gbt()
    gbt.fit(X_train, y_train)
    predictions["Gradient_boosting"] = gbt.predict(X_test)

    # Pure MLP
    mlp = make_mlp()
    mlp.fit(X_train, y_train)
    predictions["Data_MLP"] = mlp.predict(X_test)

    # Residual MLP
    residual_model = make_mlp()
    residual_model.fit(X_train, y_train - p_train)
    predictions["Residual_MLP"] = p_test + residual_model.predict(X_test)

    # Physics-guided NN: select lambda using validation only
    lambda_rows = []
    best_lambda = None
    best_val_mae = np.inf
    best_bundle = None

    for lam in PHYSICS_LAMBDAS:
        model_pg, scaler_pg = train_physics_guided_nn(
            X_train, y_train, p_train, lam=lam
        )
        pred_val = predict_torch(model_pg, scaler_pg, X_val)
        val_mae = mean_absolute_error(y_val, pred_val)

        lambda_rows.append({"lambda": lam, "val_MAE_W": val_mae})

        if val_mae < best_val_mae:
            best_val_mae = val_mae
            best_lambda = lam
            best_bundle = (model_pg, scaler_pg)

    predictions["Physics_guided_NN"] = predict_torch(
        best_bundle[0], best_bundle[1], X_test
    )

    for name, pred in predictions.items():
        row = metrics_dict(y_test, pred)
        row["model"] = name
        results.append(row)

    return {
        "metrics": pd.DataFrame(results).set_index("model").sort_values("MAE_W"),
        "predictions": predictions,
        "best_lambda": best_lambda,
        "lambda_table": pd.DataFrame(lambda_rows),
        "parasitic_coeffs": parasitic
    }

